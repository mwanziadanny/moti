// Typed-by-convention API surface. Every network call in the app goes through here.
import { http } from './client'

export const api = {
  auth: {
    me: () => http.get('/api/auth/me'),
    login: (body) => http.post('/api/auth/login', body),
    register: (body) => http.post('/api/auth/register', body),
    logout: () => http.post('/api/auth/logout'),
    forgotPassword: (body) => http.post('/api/auth/forgot-password', body),
    resetPassword: (body) => http.post('/api/auth/reset-password', body),
  },
  account: {
    update: (body) => http.patch('/api/account', body),
    changePassword: (body) => http.post('/api/account/password', body),
    remove: (password) => http.delete('/api/account', { password }),
  },
  catalog: {
    taxonomy: () => http.get('/api/taxonomy'),
    home: () => http.get('/api/home'),
    landing: (query) => http.get('/api/landing', query),
    suggest: (q) => http.get('/api/search/suggest', { q }),
    packages: () => http.get('/api/packages'),
    page: (slug) => http.get(`/api/pages/${slug}`),
    seo: (path) => http.get('/api/seo', { path }),
    sitemap: () => http.get('/api/sitemap'),
    contact: (body) => http.post('/api/contact', body),
  },
  vehicles: {
    search: (filters) => http.get('/api/vehicles', filters),
    get: (slug) => http.get(`/api/vehicles/${slug}`),
    related: (id) => http.get(`/api/vehicles/${id}/related`),
    view: (id) => http.post(`/api/vehicles/${id}/view`),
    event: (type, vehicleId, meta) => http.post('/api/events', { type, vehicleId, meta }),
    create: (data, submit) => http.post('/api/vehicles', { data, submit }),
    update: (id, data, submit) => http.patch(`/api/vehicles/${id}`, { data, submit }),
    setStatus: (id, action) => http.post(`/api/vehicles/${id}/status`, { action }),
    remove: (id) => http.delete(`/api/vehicles/${id}`),
    mine: (query) => http.get('/api/me/vehicles', query),
    quota: () => http.get('/api/me/quota'),
    upload: (body) => http.post('/api/uploads', body),
  },
  seller: {
    analytics: (days) => http.get('/api/me/analytics', { days }),
    leads: (query) => http.get('/api/me/leads', query),
  },
  dealers: {
    list: (query) => http.get('/api/dealers', query),
    get: (slug) => http.get(`/api/dealers/${slug}`),
    mine: () => http.get('/api/dealer'),
    update: (body) => http.patch('/api/dealer', body),
    staff: () => http.get('/api/dealer/staff'),
    addStaff: (body) => http.post('/api/dealer/staff', body),
    removeStaff: (userId) => http.delete(`/api/dealer/staff/${userId}`),
  },
  favourites: {
    ids: () => http.get('/api/favourites/ids'),
    list: (query) => http.get('/api/favourites', query),
    add: (vehicleId) => http.post('/api/favourites', { vehicleId }),
    remove: (vehicleId) => http.delete(`/api/favourites/${vehicleId}`),
  },
  conversations: {
    list: (side) => http.get('/api/conversations', { side }),
    unread: () => http.get('/api/conversations/unread'),
    get: (id) => http.get(`/api/conversations/${id}`),
    start: (vehicleId, body) => http.post('/api/conversations', { vehicleId, body }),
    send: (id, body) => http.post(`/api/conversations/${id}/messages`, { body }),
  },
  notifications: {
    list: () => http.get('/api/notifications'),
    markRead: (ids) => http.post('/api/notifications/read', { ids }),
  },
  reports: {
    create: (body) => http.post('/api/reports', body),
  },
  payments: {
    create: (body) => http.post('/api/payments', body),
    get: (id) => http.get(`/api/payments/${id}`),
    list: (query) => http.get('/api/payments', query),
  },
  admin: {
    overview: (days) => http.get('/api/admin/overview', { days }),
    vehicles: (query) => http.get('/api/admin/vehicles', query),
    vehicle: (id) => http.get(`/api/admin/vehicles/${id}`),
    moderate: (id, action, note) => http.post(`/api/admin/vehicles/${id}/moderate`, { action, note }),
    bulk: (ids, action, note) => http.post('/api/admin/vehicles/bulk', { ids, action, note }),
    changeSeller: (id, sellerId) => http.post(`/api/admin/vehicles/${id}/seller`, { sellerId }),
    users: (query) => http.get('/api/admin/users', query),
    updateUser: (id, body) => http.patch(`/api/admin/users/${id}`, body),
    sellers: (q) => http.get('/api/admin/sellers', { q }),
    vehicleLookup: (q) => http.get('/api/admin/vehicles-lookup', { q }),
    dealers: (query) => http.get('/api/admin/dealers', query),
    updateDealer: (id, body) => http.patch(`/api/admin/dealers/${id}`, body),
    reports: (query) => http.get('/api/admin/reports', query),
    resolveReport: (id, action, note) => http.post(`/api/admin/reports/${id}`, { action, note }),
    payments: (query) => http.get('/api/admin/payments', query),
    refund: (id) => http.post(`/api/admin/payments/${id}/refund`),
    conversations: (query) => http.get('/api/admin/conversations', query),
    conversation: (id) => http.get(`/api/admin/conversations/${id}`),
    removeMessage: (id) => http.delete(`/api/admin/messages/${id}`),
    list: (resource, query) => http.get(`/api/admin/${resource}`, query),
    create: (resource, body) => http.post(`/api/admin/${resource}`, body),
    update: (resource, id, body) => http.patch(`/api/admin/${resource}/${id}`, body),
    remove: (resource, id) => http.delete(`/api/admin/${resource}/${id}`),
    settings: () => http.get('/api/admin/settings'),
    updateSettings: (body) => http.patch('/api/admin/settings', body),
    auditLogs: (query) => http.get('/api/admin/audit-logs', query),
    outbox: (query) => http.get('/api/admin/outbox', query),
    contactMessages: () => http.get('/api/admin/contact-messages'),
    resetDemo: () => http.post('/api/admin/reset-demo'),
  },
}
